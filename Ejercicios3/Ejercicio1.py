#Mostrar numeros en un rango de numeros

#Solicitar limites del ejercicio
limite_a = int(input("Dame el limite A: "))
limite_b = int(input("Dame el limite B: "))

#por la variable veces en un rango del limite a y el b
#escribir la variable veces
for veces in range(limite_a, limite_b+1):
    print(veces)